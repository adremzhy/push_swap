#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t	len;
	char	*new_string;
	size_t	i;

	len = ft_strlen(s);
	new_string = malloc(sizeof(char) * (len + 1));
	if (!new_string)
		return (NULL);
	i = 0;
	while (s[i])
	{
		new_string[i] = s[i];
		i++;
	}
	new_string[i] = '\0';
	return (new_string);
}
